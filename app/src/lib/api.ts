/** Every call the UI makes to the server, in one place. The server is the only owner of state: callers write through
 *  here and then let the sync feed (or an explicit refresh) bring the new truth back. */
import { ipc } from "./ipc";
import type {
  DayResponse,
  DeviceRow,
  EventInput,
  ArmCommand,
  ArmSnapshot,
  HistoryMessage,
  MemoryChange,
  MemoryFile,
  MemoryFileInfo,
  MemoryOverview,
  MemoryProposal,
  PlanResponse,
  PlanWrite,
  ProactiveSettings,
  StudySubject, StudyToday, StudyStats, StudySource, StudyOutputs, StudyNoteRow, StudyNote, StudyCard, StudyTopic,
  StudyHit, StudyHint, StudyQuestion, StudyMarked, StudyAttempt, StudyTest, StudyNotebook, StudyPage, InkStroke,
  StudyBoard, BoardItem,
} from "./types";

const q = (o: Record<string, string | number>) => new URLSearchParams(Object.entries(o).map(([k, v]) => [k, String(v)])).toString();

export const api = {
  arm: () => ipc.api<ArmSnapshot>("GET", "/arm"),
  armCommand: (c: ArmCommand) => ipc.api<{ ok: boolean }>("POST", "/arm/command", c),
  plan: (start: string, days: number) => ipc.api<PlanResponse>("GET", `/plan?${q({ start, days })}`),
  planAdd: (e: EventInput) => ipc.api<PlanWrite>("POST", "/plan", e),
  planEdit: (id: string, patch: Partial<EventInput>) => ipc.api<PlanWrite>("PATCH", `/plan/${id}`, patch),
  planStatus: (id: string, status: "planned" | "done" | "skipped") => ipc.api<PlanWrite>("POST", `/plan/${id}/status`, { status }),
  planRemove: (id: string) => ipc.api<{ ok: boolean }>("DELETE", `/plan/${id}`),
  day: (date: string) => ipc.api<DayResponse>("GET", `/day/${date}`),
  setNote: (date: string, text: string) => ipc.api<DayResponse>("PUT", `/day/${date}`, { text }),

  memoryFiles: () => ipc.api<{ files: MemoryFileInfo[] }>("GET", "/memory"),
  memoryFile: (key: string) => ipc.api<MemoryFile>("GET", `/memory/${key}`),
  memoryEdit: (key: string, action: "add" | "replace" | "remove", text: string, match = "") =>
    ipc.api<{ applied: number; rejected: { why: string }[] }>("POST", `/memory/${key}`, { action, text, match }),
  memoryLog: (last = 60) => ipc.api<{ changes: MemoryChange[] }>("GET", `/memory/log?last=${last}`),
  memoryUndo: (n: number) => ipc.api<{ file: string; action: string }>("POST", `/memory/log/${n}/undo`),

  memoryOverview: () => ipc.api<MemoryOverview>("GET", "/memory/overview"),
  proposals: () => ipc.api<{ proposals: MemoryProposal[] }>("GET", "/memory/proposals"),
  answerProposal: (id: string, verdict: "accept" | "reject") => ipc.api<{ ok: boolean; applied: number }>("POST", `/memory/proposals/${id}/${verdict}`),

  settings: () => ipc.api<{ proactive: ProactiveSettings }>("GET", "/settings"),
  saveSettings: (patch: Partial<ProactiveSettings>) => ipc.api<{ proactive: ProactiveSettings }>("PUT", "/settings", patch),

  devices: () => ipc.api<{ devices: DeviceRow[] }>("GET", "/devices"),
  revoke: (id: string) => ipc.api<{ ok: boolean }>("DELETE", `/devices/${id}`),
  pairCode: () => ipc.api<{ code: string; expires_in: number }>("POST", "/devices/pair-code"),

  history: (n = 80) => ipc.api<{ messages: HistoryMessage[] }>("GET", `/chat/history?n=${n}`),

  // ---- study
  studyToday: () => ipc.api<StudyToday>("GET", "/study/today"),
  studySubjects: () => ipc.api<{ subjects: StudySubject[] }>("GET", "/study/subjects"),
  studyAddSubject: (name: string, color?: string) => ipc.api<StudySubject>("POST", "/study/subjects", { name, color }),
  studySources: (subject?: string) => ipc.api<{ sources: StudySource[] }>("GET", `/study/sources${subject ? "?" + q({ subject }) : ""}`),
  studySource: (id: string) => ipc.api<StudySource & { outputs: StudyOutputs }>("GET", `/study/sources/${id}`),
  studyImport: (b: { subject: string; title?: string; mime: string; data?: string; text?: string }) => ipc.api<StudySource>("POST", "/study/sources", b),
  studyRetry: (id: string) => ipc.api<StudySource>("POST", `/study/sources/${id}/retry`),
  studyDeleteSource: (id: string) => ipc.api<{ ok: boolean }>("DELETE", `/study/sources/${id}`),
  studyFile: (id: string) => ipc.api<{ mime: string; data: string }>("GET", `/study/files/${id}/data`),
  studyNotes: (subject?: string, query = "") => ipc.api<{ notes: StudyNoteRow[] }>("GET", `/study/notes?${q({ ...(subject ? { subject } : {}), q: query })}`),
  studyNote: (id: string) => ipc.api<StudyNote>("GET", `/study/notes/${id}`),
  studyAddNote: (b: { subject: string; title: string; body: string; topic?: string }) => ipc.api<StudyNote>("POST", "/study/notes", b),
  studyEditNote: (id: string, p: Partial<{ title: string; body: string; topic: string }>) => ipc.api<StudyNote>("PATCH", `/study/notes/${id}`, p),
  studyDeleteNote: (id: string) => ipc.api<{ ok: boolean }>("DELETE", `/study/notes/${id}`),
  studySearch: (query: string, subject?: string) => ipc.api<{ results: StudyHit[] }>("GET", `/study/search?${q({ q: query, ...(subject ? { subject } : {}) })}`),
  studyTopics: (subject?: string) => ipc.api<{ topics: StudyTopic[]; weak: { id: string; name: string; weakness: number }[] }>("GET", `/study/topics${subject ? "?" + q({ subject }) : ""}`),
  studyRenameTopic: (id: string, name: string) => ipc.api<unknown>("PATCH", `/study/topics/${id}`, { name }),
  studyMergeTopic: (id: string, into: string) => ipc.api<unknown>("PATCH", `/study/topics/${id}`, { merge_into: into }),
  studyCards: (subject?: string, state?: string) => ipc.api<{ cards: StudyCard[] }>("GET", `/study/cards?${q({ ...(subject ? { subject } : {}), ...(state ? { state } : {}) })}`),
  studyDraftCards: (b: { note_id?: string; subject?: string; text?: string; n?: number }) => ipc.api<{ cards: StudyCard[] }>("POST", "/study/cards/draft", b),
  studyEditCard: (id: string, p: Partial<{ front: string; back: string; topic: string; state: string }>) => ipc.api<StudyCard>("PATCH", `/study/cards/${id}`, p),
  studyApprove: (id: string) => ipc.api<StudyCard>("POST", `/study/cards/${id}/approve`),
  studyDeleteCard: (id: string) => ipc.api<{ ok: boolean }>("DELETE", `/study/cards/${id}`),
  studyDue: (subject?: string, limit = 30) => ipc.api<{ cards: StudyCard[] }>("GET", `/study/due?${q({ ...(subject ? { subject } : {}), limit })}`),
  studyReview: (id: string, grade: 0 | 1 | 2) => ipc.api<StudyCard>("POST", `/study/cards/${id}/review`, { grade }),
  studyStats: (subject?: string) => ipc.api<StudyStats>("GET", `/study/stats${subject ? "?" + q({ subject }) : ""}`),
  studyTutor: (question: string, subject: string | undefined, step: number, history = "") => ipc.api<StudyHint>("POST", "/study/tutor", { question, subject, step, history }),
  studyPractice: (subject: string, kind: string, topic?: string) => ipc.api<StudyQuestion>("POST", "/study/practice", { subject, kind, topic }),
  studyAnswer: (id: string, answer: string, images: { mime: string; data: string }[] = []) => ipc.api<StudyMarked>("POST", `/study/practice/${id}/answer`, { answer, images }),
  studyMarkPaper: (b: { subject: string; question: string; answer: string; scheme: string; marks: number; topic?: string; images?: { mime: string; data: string }[] }) => ipc.api<{ score: number; marks: number; feedback: string; next: string }>("POST", "/study/papers/mark", b),
  studyAttempts: (subject?: string) => ipc.api<{ attempts: StudyAttempt[] }>("GET", `/study/attempts${subject ? "?" + q({ subject }) : ""}`),
  studyTests: () => ipc.api<{ tests: StudyTest[] }>("GET", "/study/tests"),
  studyAddTest: (b: { subject: string; title: string; date: string; topics?: string[] }) => ipc.api<{ test: StudyTest; blocks: { id: string; date: string }[] }>("POST", "/study/tests", b),
  studyDeleteTest: (id: string) => ipc.api<{ ok: boolean }>("DELETE", `/study/tests/${id}`),
  studyNotebooks: () => ipc.api<{ notebooks: StudyNotebook[] }>("GET", "/study/notebooks"),
  studyAddNotebook: (title: string, subject?: string) => ipc.api<StudyNotebook>("POST", "/study/notebooks", { title, subject }),
  studyNotebook: (id: string) => ipc.api<StudyNotebook>("GET", `/study/notebooks/${id}`),
  studyDeleteNotebook: (id: string) => ipc.api<{ ok: boolean }>("DELETE", `/study/notebooks/${id}`),
  studyAddPage: (nid: string, background = "lined") => ipc.api<StudyPage>("POST", `/study/notebooks/${nid}/pages`, { background }),
  studyPage: (id: string) => ipc.api<StudyPage>("GET", `/study/pages/${id}`),
  studySavePage: (id: string, strokes: InkStroke[], background?: string) => ipc.api<StudyPage>("PUT", `/study/pages/${id}`, { strokes, background }),
  studyDeletePage: (id: string) => ipc.api<{ ok: boolean }>("DELETE", `/study/pages/${id}`),
  studyPdf: (nid: string) => ipc.api<{ mime: string; data: string }>("GET", `/study/notebooks/${nid}/pdf/data`),
  studyBoards: () => ipc.api<{ boards: { id: string; title: string; updated: string }[] }>("GET", "/study/boards"),
  studyAddBoard: (title: string, subject?: string) => ipc.api<StudyBoard>("POST", "/study/boards", { title, subject }),
  studyBoard: (id: string) => ipc.api<StudyBoard>("GET", `/study/boards/${id}`),
  studyPutItem: (bid: string, it: Partial<BoardItem> & { kind: BoardItem["kind"] }) => ipc.api<BoardItem>("PUT", `/study/boards/${bid}/items`, it),
  studyDeleteItem: (bid: string, iid: string) => ipc.api<{ ok: boolean }>("DELETE", `/study/boards/${bid}/items/${iid}`),
  studyDeleteBoard: (id: string) => ipc.api<{ ok: boolean }>("DELETE", `/study/boards/${id}`),
};
